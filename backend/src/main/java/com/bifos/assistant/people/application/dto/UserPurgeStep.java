package com.bifos.assistant.people.application.dto;

/**
 * 사용자 한 사람을 정리하는 단계다. 이 순서대로 한다(ADR-20261101 / user-purge).
 *
 * <p>단계마다 트랜잭션 하나다. 한 단계가 실패하면 다음 차례에 첫 단계부터 다시 한다. 각 단계는 이미 지운 것을 다시 지워도 같은
 * 결과다. 데이터 key 와 사용자 줄은 마지막 단계에서 대화 정리가 끝났음을 확인한 뒤에만 지운다.
 */
public enum UserPurgeStep {
    /** 그룹 공개 에이전트를 그룹의 켜진 관리자에게 넘긴다. 넘겨받을 관리자가 없으면 아무것도 지우지 않고 멈춘다. */
    TRANSFER_AGENTS,
    /** 보관본 행(묶음 안 파일과 지우기 이력 포함)을 지운다. */
    DELETE_VAULT,
    /** 개인 기억, 할 일, 예약 작업, 알림, 커넥터 연결과 권한, 브라우저, 사용자를 가리키는 다른 표의 줄을 지운다. */
    DELETE_PERSONAL_DATA,
    /** 대화와 비공개 에이전트를 지운 것으로 적는다. 본문과 행은 대화 정리와 에이전트 정리가 지운다. */
    MARK_DELETED,
    /** 대화 정리가 모두 끝났으면 데이터 key 와 사용자 줄을 지운다. 아니면 다음 차례로 미룬다. */
    DELETE_USER
}
