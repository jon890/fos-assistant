CREATE TABLE content_draft_snapshot (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id BINARY(16) NOT NULL,
    revision_id BIGINT NOT NULL,
    owner_user_id BIGINT NOT NULL,
    conversation_id BIGINT NOT NULL,
    origin_execution_id BIGINT NOT NULL,
    agent_id BIGINT NOT NULL,
    connection_id BIGINT NOT NULL,
    binding_id BIGINT NOT NULL,
    connection_updated_at DATETIME(6) NOT NULL,
    binding_updated_at DATETIME(6) NOT NULL,
    policy_fingerprint CHAR(64) NOT NULL,
    schema_version INT NOT NULL,
    compiler_version VARCHAR(32) NOT NULL,
    payload_fingerprint CHAR(64) NOT NULL,
    snapshot_hash CHAR(64) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    expires_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_content_snapshot_public (public_id),
    UNIQUE KEY uk_content_snapshot_revision_binding_hash (revision_id, binding_id, snapshot_hash),
    KEY idx_content_draft_snapshot_owner_conversation (owner_user_id, conversation_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE content_draft_job (
    id BIGINT NOT NULL AUTO_INCREMENT,
    snapshot_id BIGINT NOT NULL,
    action_id BIGINT NOT NULL,
    owner_user_id BIGINT NOT NULL,
    conversation_id BIGINT NOT NULL,
    job_id CHAR(36) NULL,
    status VARCHAR(32) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    approved_by BIGINT NULL,
    approved_at DATETIME(6) NULL,
    last_checked_at DATETIME(6) NULL,
    start_claimed_at DATETIME(6) NULL,
    save_claimed_at DATETIME(6) NULL,
    stage VARCHAR(32) NULL,
    save_clicked BOOLEAN NOT NULL DEFAULT FALSE,
    error_code VARCHAR(64) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_content_job_snapshot (snapshot_id),
    UNIQUE KEY uk_content_job_action (action_id),
    UNIQUE KEY uk_content_job_id (job_id),
    KEY idx_content_draft_job_owner_conversation (owner_user_id, conversation_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

